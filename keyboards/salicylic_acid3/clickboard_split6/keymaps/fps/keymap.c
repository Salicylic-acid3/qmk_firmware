bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {

    case QK_KB_0:
        if (record->event.pressed) {
			wkeep = true;
			unregister_code(KC_S);
            register_code(KC_W);
        } else {
			wkeep = false;
            unregister_code(KC_W);
			if (skeep) {
				register_code(KC_S);
			}
        }
        break;

    case QK_KB_1:
        if (record->event.pressed) {
			akeep = true;
			unregister_code(KC_D);
            register_code(KC_A);
        } else {
			akeep = false;
            unregister_code(KC_A);
			if (dkeep) {
				register_code(KC_D);
			}
        }
        break;

    case QK_KB_2:
        if (record->event.pressed) {
			skeep = true;
			unregister_code(KC_W);
            register_code(KC_S);
        } else {
			skeep = false;
            unregister_code(KC_S);
			if (wkeep) {
				register_code(KC_W);
			}
        }
        break;

    case QK_KB_3:
        if (record->event.pressed) {
			dkeep = true;
			unregister_code(KC_A);
            register_code(KC_D);
        } else {
			dkeep = false;
            unregister_code(KC_D);
			if (akeep) {
				register_code(KC_A);
			}
        }
        break;


    }
    return true;
};
